//! Reproduce the Unicode translation tables in the #201 migration using the pinned Rust
//! toolchain/unicode-normalization. Run `cargo run -p vink-app --example draft_search_migration`.
//! A future Unicode upgrade needs a NEW migration; never overwrite an applied migration.
use unicode_normalization::{UnicodeNormalization, char::is_combining_mark};

fn literal(s: &str) -> String {
    // Keep control/Unicode whitespace visible and preserve bytes through editors/Git.
    let mut out = String::from("U&'");
    for c in s.chars() {
        match c {
            '\'' => out.push_str("''"),
            '\\' => out.push_str("\\\\"),
            c if c != ' ' && (c.is_control() || c.is_whitespace()) => {
                out.push_str(&format!("\\{:04x}", c as u32));
            }
            c => out.push(c),
        }
    }
    out.push('\'');
    out
}

fn main() {
    let whitespace: String = (1..=0x10ffff)
        .filter_map(char::from_u32)
        .filter(|c| c.is_whitespace())
        .collect();
    let mut from = String::new();
    let mut to = String::new();
    let mut remove = String::new();
    for c in (1..=0x10ffff).filter_map(char::from_u32) {
        if is_combining_mark(c) {
            remove.push(c);
            continue;
        }
        // NFD runs first. Only decomposed scalars need translation. This also excludes
        // U+0130, the only full lowercase mapping that expands to multiple scalars.
        if !c.to_string().nfd().eq(std::iter::once(c)) {
            continue;
        }
        let mapped: String = c
            .to_lowercase()
            .map(|x| {
                if x == 'đ' {
                    'd'
                } else if x.is_whitespace() {
                    ' '
                } else {
                    x
                }
            })
            .collect();
        assert_eq!(mapped.chars().count(), 1);
        if mapped != c.to_string() {
            from.push(c);
            to.push_str(&mapped);
        }
    }
    from.push_str(&remove);
    // PostgreSQL 17 predates these Unicode canonical decompositions. The exhaustive
    // scalar parity test against PostgreSQL pins this small compatibility supplement.
    let mut nfd = "normalize(input, NFD)".to_string();
    for scalar in [
        0x105c9, 0x105e4, 0x11383, 0x11385, 0x1138e, 0x11391, 0x16d68, 0x16d69, 0x16d6a,
    ] {
        let raw = char::from_u32(scalar).unwrap().to_string();
        let decomposed: String = raw.nfd().collect();
        nfd = format!(
            "replace({nfd}, {}, {})",
            literal(&raw),
            literal(&decomposed)
        );
    }
    println!(
        "-- Private draft title comparison (#201). Generated by examples/draft_search_migration.rs.\n\
-- NFD, exact combining-mark removal and per-character lowercase/whitespace semantics of\n\
-- domain::draft_query::search_key and Web search::search_key. Punctuation is retained.\n\
-- Explicit translate tables avoid locale/contextual lowercase (e.g. final Greek sigma).\n\
-- PostgreSQL owns the stored key, including existing rows and every SQL writer.\n\
CREATE FUNCTION vink_desk_key(input text) RETURNS text\n\
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $function$\n\
    SELECT btrim(regexp_replace(translate({},\n        {},\n        {}), ' +', ' ', 'g'), ' ')\n\
$function$;\n\
ALTER TABLE working_drafts ADD COLUMN desk_title_key text\n\
    GENERATED ALWAYS AS (vink_desk_key(CASE WHEN btrim(title, {}) = '' THEN 'Chưa đặt tên' ELSE title END)) STORED;\n\
COMMENT ON COLUMN working_drafts.desk_title_key IS\n\
    'Private display-title substring/sort key; not the public discovery key. PostgreSQL maintains it atomically with title.';",
        nfd,
        literal(&from),
        literal(&to),
        literal(&whitespace)
    );
}
